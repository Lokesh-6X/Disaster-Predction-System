# Creates this project's Mosquitto config and password file from .env.
# Run once, and again after changing MQTT usernames/passwords in .env.
# -Lan listens on all network interfaces (needed when the real kit connects, Phase 6);
# by default the broker only accepts connections from this PC.
param([switch]$Lan)

. "$PSScriptRoot\_common.ps1"
$e = Read-DotEnv

if ($e['MQTT_USERNAME'] -ne 'backend') {
    Write-Warning "MQTT_USERNAME is '$($e['MQTT_USERNAME'])' but config\mosquitto\acl grants read access to 'backend'. Update the acl file to match."
}

$confDir = Join-Path $ProjectRoot 'config\mosquitto'
$dataDir = Join-Path $ProjectRoot 'data\mosquitto'
$passwdFile = Join-Path $confDir 'passwd'
$aclFile = Join-Path $confDir 'acl'
$confFile = Join-Path $confDir 'mosquitto.conf'
$passwdExe = Join-Path $MosquittoDir 'mosquitto_passwd.exe'

New-Item -ItemType Directory -Force $dataDir | Out-Null

# Password file (hashed); -c creates a new file, replacing any old one
& $passwdExe -c -b $passwdFile $e['MQTT_USERNAME'] $e['MQTT_PASSWORD']
if ($LASTEXITCODE -ne 0) { throw 'mosquitto_passwd failed' }
& $passwdExe -b $passwdFile $e['MQTT_KIT_USERNAME'] $e['MQTT_KIT_PASSWORD']
if ($LASTEXITCODE -ne 0) { throw 'mosquitto_passwd failed' }

$port = if ($e['MQTT_PORT']) { $e['MQTT_PORT'] } else { '1884' }
$bind = if ($Lan) { '' } else { ' 127.0.0.1' }

@"
# Generated by scripts\setup_broker.ps1 — edit the script, not this file.
listener $port$bind
allow_anonymous false
password_file $passwdFile
acl_file $aclFile
persistence true
persistence_location $dataDir\
log_dest stdout
log_timestamp_format %Y-%m-%dT%H:%M:%S
"@ | Set-Content -Path $confFile -Encoding ascii

Write-Host "Broker config written to $confFile (port $port$(if ($Lan) {', all interfaces'} else {', this PC only'}))."
Write-Host "Start it with: scripts\start_broker.ps1"
